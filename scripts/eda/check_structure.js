#!/usr/bin/env node
/*
 * Home-Automation-SoC — fail-closed structural validation of mapped designs (F8)
 *
 * The problem this replaces: the full-SoC flow ended in a bare Yosys `check`,
 * which prints "Found and reported N problems" and still exits 0. A design with
 * undriven outputs, multiple drivers or cells the map never handled therefore
 * passed verification silently. Only a nonzero exit status is a check.
 *
 * What is enforced here:
 *   1. `check -assert` — undriven wires, multiple drivers, port problems.
 *   2. unexpected leaf cells — anything that is not a library cell and is not
 *      declared in asic/synthesis/structural_policy.json.
 *   3. declared-gap accounting — the declared count must match, so a stale
 *      inventory is an error rather than an alibi.
 *   4. incomplete mapping — a design with no leaf cells cannot pass.
 *
 * Exit codes (deliberately three-valued, because "declared gap" is not "pass"):
 *   0  PASS     fully mapped, structurally clean
 *   1  FAIL     structural problem, unexpected cell, or stale policy
 *   2  BLOCKED  only declared gaps remain (reported by name; never a PASS)
 *
 * Usage:
 *   node scripts/eda/check_structure.js --self-test
 *       Runs the control matrix: the pre-fix silent pass, every injected
 *       defect, the stale inventory and the clean baseline.
 *   node scripts/eda/check_structure.js --script asic/synthesis/fullsoc_map.ys \
 *        --top has_soc --json build/asic_evidence/structural_check/has_soc_cells.json
 *   node scripts/eda/check_structure.js --verilog a.v,b.v --top foo [--map] \
 *        [--no-generic-techmap] [--legacy] [--json out.json]
 *
 * Logs: build/asic_evidence/structural_check/logs/<tag>.log
 */
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'build', 'asic_evidence', 'structural_check');
const LOGS = path.join(OUT, 'logs');
const POLICY = path.join(ROOT, 'asic', 'synthesis', 'structural_policy.json');
const MAP = 'build/asic_evidence/sky130_map.v';
const LIB = 'build/asic_evidence/sky130_full_subset.lib';
const CASES = 'asic/synthesis/structural_cases';

const TOOL_DIR = process.env.EDA_TOOLS || 'D:/tools/oss-cad-suite';
const env = { ...process.env };
// oss-cad-suite keeps its DLLs in lib/: without it yosys.exe fails to start.
env.PATH = [path.join(TOOL_DIR, 'bin'), path.join(TOOL_DIR, 'lib'), env.PATH].join(path.delimiter);

fs.mkdirSync(LOGS, { recursive: true });

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const flag = name => process.argv.includes(name);

function rel(p) {
  return path.relative(ROOT, path.resolve(ROOT, p)).split(path.sep).join('/');
}

// The binary is overridable so the self-test can prove that a broken external
// tool invocation is a FAIL and never a silent pass.
const YOSYS = arg('--yosys', 'yosys');

function yosys(scriptPath, logPath) {
  const r = spawnSync(YOSYS, ['-s', rel(scriptPath)], {
    cwd: ROOT, env, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024,
  });
  const text = (r.stdout || '') + (r.stderr || '');
  fs.writeFileSync(logPath, `$ ${YOSYS} -s ${rel(scriptPath)}\n\n${text}`);
  return { status: r.status === null ? 1 : r.status, text, spawnError: r.error || null };
}

function generatedScript({ files, top, map, genericTechmap, legacy, jsonPath }) {
  const lines = [];
  lines.push(`# generated by scripts/eda/check_structure.js`);
  for (const f of files) lines.push(`read_verilog -sv ${rel(f)}`);
  lines.push(`hierarchy -check -top ${top}`);
  lines.push('proc');
  lines.push('memory_collect');
  lines.push('opt_clean');
  if (map) {
    lines.push(`read_liberty -lib ${LIB}`);
    if (genericTechmap) lines.push('techmap -map +/techmap.v');
    lines.push(`techmap -map ${MAP}`);
    lines.push(`techmap -map ${MAP}`);
    lines.push('hierarchy -check');
    lines.push('opt_clean');
  }
  lines.push(`tee -o ${rel(jsonPath)} stat -top ${top} -json`);
  lines.push(legacy ? 'check' : 'check -assert');
  return lines.join('\n') + '\n';
}

// Leaf cells reachable in the report: a cell type that is also a module name is
// an instance, not a leaf. Module names in the JSON carry an RTLIL backslash.
function leafCells(report) {
  const mods = report.modules || {};
  const moduleNames = new Set(Object.keys(mods).map(n => n.replace(/^\\/, '')));
  const agg = {};
  for (const info of Object.values(mods)) {
    for (const [type, count] of Object.entries(info.num_cells_by_type || {})) {
      if (moduleNames.has(type.replace(/^\\/, ''))) continue;
      agg[type] = (agg[type] || 0) + count;
    }
  }
  return agg;
}

function evaluate({ jsonPath, top, policy, logPath }) {
  const details = [];
  if (!fs.existsSync(jsonPath)) {
    details.push(`no cell report written (${rel(jsonPath)})`);
    return { code: 1, verdict: 'FAIL', details };
  }
  let report;
  try {
    report = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  } catch (err) {
    details.push(`cell report is not valid JSON: ${err.message}`);
    return { code: 1, verdict: 'FAIL', details };
  }
  const modules = report.modules || {};
  const topKey = Object.keys(modules).find(k => k.replace(/^\\/, '') === top);
  if (!topKey) {
    details.push(`top module "${top}" is not in the report`);
    return { code: 1, verdict: 'FAIL', details };
  }

  const cells = leafCells(report);
  const total = Object.values(cells).reduce((s, n) => s + n, 0);
  const allowed = policy.allowed_cell_prefixes || [];
  const declared = (policy.declared_gaps || {})[top] || [];
  const declaredTypes = new Set(declared.map(d => d.cell));

  details.push(`${total} leaf cells, ${Object.keys(cells).length} types`);

  const unexpected = Object.entries(cells)
    .filter(([type]) => !allowed.some(p => type.startsWith(p)) && !declaredTypes.has(type))
    .sort((a, b) => b[1] - a[1]);
  if (unexpected.length) {
    for (const [type, count] of unexpected) details.push(`UNEXPECTED ${type} x${count}`);
  }

  const minCells = policy.min_leaf_cells == null ? 1 : policy.min_leaf_cells;
  if (total < minCells) details.push(`incomplete mapping: only ${total} leaf cells (minimum ${minCells})`);

  const gaps = [];
  for (const d of declared) {
    const actual = cells[d.cell] || 0;
    if (actual !== d.expected) {
      details.push(`STALE POLICY ${d.cell}: declared ${d.expected}, found ${actual}`);
    } else {
      gaps.push(`${d.cell} x${actual} — ${d.reason || 'declared gap'}`);
    }
  }

  if (unexpected.length || total < minCells || details.some(l => l.startsWith('STALE POLICY'))) {
    return { code: 1, verdict: 'FAIL', details };
  }
  if (gaps.length) {
    for (const g of gaps) details.push(`GAP ${g}`);
    return { code: 2, verdict: 'BLOCKED', details };
  }
  return { code: 0, verdict: 'PASS', details };
}

function report(result, tag) {
  console.log(`STRUCTURAL_CHECK: ${result.verdict} (${tag})`);
  for (const d of result.details) console.log(`  ${d}`);
  console.log(`STRUCTURAL_CHECK: ${result.verdict === 'PASS' ? 'PASS' : result.verdict === 'BLOCKED' ? 'BLOCKED' : 'FAIL'}`);
}

function runGenerated({ tag, files, top, map = false, genericTechmap = true, legacy = false }) {
  const jsonPath = path.join(OUT, `${tag}_cells.json`);
  const scriptPath = path.join(OUT, `${tag}.ys`);
  fs.writeFileSync(scriptPath, generatedScript({ files, top, map, genericTechmap, legacy, jsonPath }));
  const logPath = path.join(LOGS, `${tag}.log`);
  const run = yosys(scriptPath, logPath);
  const problems = Number((run.text.match(/Found and reported (\d+) problems/) || [0, 0])[1] || 0);
  if (legacy) {
    // Pre-fix behaviour: the exit status ignores the problems it just printed.
    return { code: run.status, verdict: 'LEGACY', details: [`${problems} problem(s) reported, yosys exit ${run.status}`], problems, logPath };
  }
  if (run.status !== 0) {
    return { code: 1, verdict: 'FAIL', details: [`yosys exited ${run.status} (see ${rel(logPath)})`], logPath };
  }
  const policy = JSON.parse(fs.readFileSync(POLICY, 'utf8'));
  return { ...evaluate({ jsonPath, top, policy, logPath }), logPath };
}

// ---- self-test: every control must land on its expected exit code ----------
if (flag('--self-test')) {
  const cases = [
    { tag: 'legacy-undriven', files: [`${CASES}/undriven_top.v`], top: 'undriven_top', legacy: true, expect: 0, expectProblems: true,
      what: 'pre-fix flow (bare check) passes a design with undriven outputs' },
    { tag: 'undriven', files: [`${CASES}/undriven_top.v`], top: 'undriven_top', expect: 1,
      what: 'check -assert rejects undriven outputs' },
    { tag: 'multidriver', files: [`${CASES}/multidriver_top.v`], top: 'multidriver_top', expect: 1,
      what: 'multiple drivers rejected' },
    { tag: 'undeclared-memory', files: [`${CASES}/undeclared_memory_top.v`], top: 'undeclared_memory_top', expect: 1,
      what: 'undeclared inferred memory rejected' },
    { tag: 'stale-policy', files: [`${CASES}/policy_mismatch_case.v`], top: 'has_soc', expect: 1,
      what: 'declared memory count must match the design' },
    { tag: 'unmapped-div', files: [`${CASES}/unmapped_div_top.v`], top: 'unmapped_div_top', map: true, genericTechmap: false, expect: 1,
      what: 'cell the map does not handle is reported, not shipped' },
    { tag: 'clean-baseline', files: [`${CASES}/clean_baseline_top.v`], top: 'clean_baseline_top', map: true, expect: 0,
      what: 'fully mapped design passes' },
  ];

  let failures = 0;
  for (const c of cases) {
    const r = runGenerated(c);
    const okCode = r.code === c.expect;
    const okProblems = c.expectProblems ? r.problems > 0 : true;
    const ok = okCode && okProblems;
    if (!ok) failures++;
    const observed = r.verdict === 'LEGACY' ? `exit ${r.code}, ${r.problems} problem(s)` : `exit ${r.code}`;
    console.log(`${ok ? 'ok  ' : 'FAIL'} ${c.tag}: expected exit ${c.expect}${c.expectProblems ? ' with reported problems' : ''}, got ${observed} — ${c.what}`);
    if (!ok) for (const d of r.details) console.log(`       ${d}`);
  }
  // ---- evaluator controls: failure modes of the report itself --------------
  // These drive evaluate() directly, so a missing, empty, truncated, stale or
  // wrong-module report cannot be mistaken for a clean design.
  const EVAL = path.join(OUT, 'selftest');
  fs.mkdirSync(EVAL, { recursive: true });
  const policy = {
    allowed_cell_prefixes: ['sky130_fd_sc_hd__'],
    min_leaf_cells: 1,
    declared_gaps: { has_soc: [{ cell: '$mem_v2', expected: 4, reason: 'selftest fixture' }] },
  };
  const mod = cells => ({ modules: { '\\has_soc': { num_cells_by_type: cells } } });
  const writeJson = (name, obj) => {
    const p = path.join(EVAL, name);
    fs.writeFileSync(p, typeof obj === 'string' ? obj : JSON.stringify(obj));
    return p;
  };
  // A clean PASS needs a policy with no declared gaps: the project policy
  // declares $mem_v2 x4, so a design without those four cells is stale.
  const policyClean = { allowed_cell_prefixes: ['sky130_fd_sc_hd__'], min_leaf_cells: 1, declared_gaps: {} };
  const evalCases = [
    ['clean mapped design passes', writeJson('clean.json', mod({ sky130_fd_sc_hd__inv_1: 3, sky130_fd_sc_hd__and2_1: 2 })), 0, 'PASS', policyClean],
    ['declared gap only is BLOCKED, not PASS', writeJson('gap.json', mod({ sky130_fd_sc_hd__inv_1: 3, '$mem_v2': 4 })), 2, 'BLOCKED'],
    ['report file missing', path.join(EVAL, 'absent.json'), 1, 'FAIL'],
    ['truncated / invalid JSON report', writeJson('broken.json', '{"modules": {'), 1, 'FAIL'],
    ['empty mapping result', writeJson('empty.json', mod({})), 1, 'FAIL'],
    ['undeclared generic cell', writeJson('unexpected.json', mod({ sky130_fd_sc_hd__inv_1: 1, '$dff': 2 })), 1, 'FAIL'],
    ['stale declared gap count', writeJson('stale.json', mod({ sky130_fd_sc_hd__inv_1: 1, '$mem_v2': 3 })), 1, 'FAIL'],
    ['report from a different top', writeJson('wrongtop.json', { modules: { '\\other': { num_cells_by_type: { sky130_fd_sc_hd__inv_1: 2 } } } }), 1, 'FAIL'],
  ];
  let evalBad = 0;
  for (const [what, jsonPath, expectCode, expectVerdict, pol] of evalCases) {
    const r = evaluate({ jsonPath, top: 'has_soc', policy: pol || policy, logPath: path.join(LOGS, 'selftest.log') });
    const ok = r.code === expectCode && r.verdict === expectVerdict;
    if (!ok) evalBad++;
    // Control output deliberately avoids the bare token "FAIL": the gate's
    // failure-pattern scan would otherwise reject a fully successful self-test.
    console.log(`${ok ? 'ok  ' : 'wrong'} eval ${String(what).padEnd(40)} expected ${expectCode}/${expectVerdict.toLowerCase()}, got ${r.code}/${r.verdict.toLowerCase()}`);
  }

  // ---- broken external tool invocation ------------------------------------
  // A missing or unusable yosys must be a FAIL, never an empty "no problems".
  const badTool = spawnSync(process.execPath, [__filename,
    '--yosys', 'definitely-not-a-yosys',
    '--verilog', `${CASES}/clean_baseline_top.v`, '--top', 'clean_baseline_top', '--tag', 'broken-tool'],
    { cwd: ROOT, env, encoding: 'utf8' });
  const toolOk = badTool.status === 1;
  if (!toolOk) evalBad++;
  console.log(`${toolOk ? 'ok  ' : 'wrong'} eval ${'broken external tool invocation'.padEnd(40)} expected exit 1, got ${badTool.status}`);

  const total = cases.length + evalCases.length + 1;
  const bad = failures + evalBad;
  console.log(bad === 0
    ? `STRUCTURAL_CHECK: SELF-TEST PASS (${total}/${total} controls behaved as specified)`
    : `STRUCTURAL_CHECK: SELF-TEST FAIL (${bad}/${total} controls wrong)`);
  process.exit(bad === 0 ? 0 : 1);
}

// ---- single target --------------------------------------------------------
const script = arg('--script');
const top = arg('--top');
if (!top) {
  console.error('usage: --script <file.ys> --top <name> --json <file> | --verilog <a.v,b.v> --top <name> [--map] | --self-test');
  process.exit(1);
}
const tag = arg('--tag', 'target');
let result;
if (script) {
  const logPath = path.join(LOGS, `${tag}.log`);
  const run = yosys(script, logPath);
  const jsonPath = path.resolve(ROOT, arg('--json', path.join(OUT, `${tag}_cells.json`)));
  if (run.status !== 0) {
    result = { code: 1, verdict: 'FAIL', details: [`yosys exited ${run.status} (see ${rel(logPath)})`] };
  } else if (flag('--legacy')) {
    const problems = Number((run.text.match(/Found and reported (\d+) problems/) || [0, 0])[1] || 0);
    result = { code: run.status, verdict: 'LEGACY', details: [`${problems} problem(s) reported, yosys exit ${run.status}`] };
  } else {
    const policy = JSON.parse(fs.readFileSync(POLICY, 'utf8'));
    result = evaluate({ jsonPath, top, policy, logPath });
  }
} else {
  const files = arg('--verilog', '').split(',').map(s => s.trim()).filter(Boolean);
  if (!files.length) {
    console.error('--verilog <comma-separated files> is required without --script');
    process.exit(1);
  }
  result = runGenerated({
    tag, files, top,
    map: flag('--map'),
    genericTechmap: !flag('--no-generic-techmap'),
    legacy: flag('--legacy'),
  });
}

report(result, `top=${top}`);
process.exit(result.code);
