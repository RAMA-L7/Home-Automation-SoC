#!/usr/bin/env python3
"""Generate a synthesizable boot ROM module from a $readmemh image.

The behavioural rtl/rtl_top/boot_rom.sv keeps its contents in a `mem` array
filled by $readmemh. Yosys infers a `$mem_v2` for that array, which no
standard-cell library can implement, so the design can never be mapped as-is.

This script emits the SAME module interface with the contents baked into a
case statement. That is ordinary combinational logic after synthesis (a tree of
AND/OR gates), so it maps to sky130_fd_sc_hd cells with no memory macro and no
$mem cell, and it keeps the boot image that the software relies on.

Usage:
    python3 scripts/fw_build/gen_rom_rtl.py <image.hex> <out.v>

The image is `$readmemh` format: one 32-bit word per line, address order, and
address 0 is the first line. Words the image does not cover read as the
behavioural module's fill value, 32'h0000_0013 (NOP).
"""
import hashlib
import pathlib
import sys

FILL = "32'h0000_0013"


def read_image(path: pathlib.Path):
    words = []
    for n, line in enumerate(path.read_text().splitlines(), 1):
        s = line.split("//")[0].strip()
        if not s:
            continue
        if s.startswith("@"):
            raise SystemExit(f"line {n}: address directives are not supported ({s})")
        words.append(int(s, 16) & 0xFFFFFFFF)
    return words


def emit(words, src_name, src_sha, addr_width=14, data_width=32):
    words_total = 1 << (addr_width - 2)
    if len(words) > words_total:
        raise SystemExit(f"image has {len(words)} words, aperture holds {words_total}")
    sel_bits = addr_width - 2

    cases = "\n".join(
        f"        {sel_bits}'d{i}: rom_decode = 32'h{w:08X};" for i, w in enumerate(words)
    )

    return f"""//------------------------------------------------------------------------------
// boot_rom — SYNTHESIZABLE standard-cell ROM  *** GENERATED FILE ***
//
// Generated by scripts/fw_build/gen_rom_rtl.py. Do not edit by hand.
//
//   image : {src_name}
//   sha256: {src_sha}
//   words : {len(words)} of {words_total} (rest filled with 32'h0000_0013 = NOP)
//
// Interface, read latency and write rejection are identical to the behavioural
// rtl/rtl_top/boot_rom.sv, so this module is a drop-in replacement:
//   * instruction port: gnt in the request cycle, rvalid + rdata on the next;
//   * AXI4-Lite read: one-cycle response, same timing;
//   * AXI4-Lite write: accepted, answered with SLVERR (2'b10), no state change.
//
// MEM_FILE / INIT_FILE exist only so existing instantiations keep compiling.
// They are IGNORED: the contents are compiled into the decode logic. Changing
// the boot image means regenerating this file.
//------------------------------------------------------------------------------
module boot_rom #(
  parameter int ADDR_WIDTH = {addr_width},
  parameter int DATA_WIDTH = {data_width},
  // verilog_lint: waive explicit-parameter-storage-type
  parameter MEM_FILE   = "",   // IGNORED — contents are baked in
  // verilog_lint: waive explicit-parameter-storage-type
  parameter INIT_FILE  = ""    // IGNORED — contents are baked in
) (
  input  logic                   clk,
  input  logic                   reset_n,
  input  logic                   req,
  input  logic [ADDR_WIDTH-1:0]  addr,
  output logic                   gnt,
  output logic [DATA_WIDTH-1:0]  rdata,
  output logic                   rvalid,
  input  logic                   awvalid,
  output logic                   awready,
  input  logic [DATA_WIDTH-1:0]  awaddr,
  input  logic                   wvalid,
  output logic                   wready,
  input  logic [DATA_WIDTH-1:0]  wdata,
  input  logic [3:0]             wstrb,
  output logic                   bvalid,
  input  logic                   bready,
  output logic [1:0]             bresp,
  input  logic                   arvalid,
  output logic                   arready,
  input  logic [DATA_WIDTH-1:0]  araddr,
  output logic                   r_rvalid,
  input  logic                   r_rready,
  output logic [DATA_WIDTH-1:0]  r_rdata,
  output logic [1:0]             r_rresp
);

  localparam int WORDS = 1 << (ADDR_WIDTH - 2);

  // Read-only decode: pure combinational logic after synthesis.
  function automatic [DATA_WIDTH-1:0] rom_decode(input logic [ADDR_WIDTH-1:0] a);
    logic [ADDR_WIDTH-3:0] sel;
    begin
      sel = a[ADDR_WIDTH-1:2];
      case (sel)
{cases}
        default: rom_decode = {FILL};   // fill word the image does not cover
      endcase
    end
  endfunction

  //--------------------------------------------------------------------------
  // Instruction port — identical timing to the behavioural module
  //--------------------------------------------------------------------------
  typedef enum logic {{IF_IDLE, IF_DATA}} if_state_e;
  if_state_e if_state;
  logic [ADDR_WIDTH-1:0] if_addr_q;

  assign gnt    = (if_state == IF_IDLE) && req;
  assign rvalid = (if_state == IF_DATA);
  assign rdata  = rom_decode(if_addr_q);

  always_ff @(posedge clk or negedge reset_n) begin
    if (!reset_n) begin
      if_state  <= IF_IDLE;
      if_addr_q <= '0;
    end else begin
      case (if_state)
        IF_IDLE: if (req) begin
                   if_addr_q <= addr;
                   if_state  <= IF_DATA;
                 end
        IF_DATA: if_state <= IF_IDLE;
        default: ;
      endcase
    end
  end

  //--------------------------------------------------------------------------
  // AXI4-Lite slave — read-only, writes answered with SLVERR
  //--------------------------------------------------------------------------
  typedef enum logic [1:0] {{AX_IDLE, AX_RRESP, AX_BRESP}} ax_state_e;
  ax_state_e ax_state;
  logic [ADDR_WIDTH-1:0] ax_raddr_q;

  assign awready = (ax_state == AX_IDLE) & ~arvalid;
  assign wready  = (ax_state == AX_IDLE) & ~arvalid;
  assign arready = (ax_state == AX_IDLE) & ~awvalid;

  always_ff @(posedge clk or negedge reset_n) begin
    if (!reset_n) begin
      ax_state   <= AX_IDLE;
      ax_raddr_q <= '0;
    end else begin
      case (ax_state)
        AX_IDLE: begin
          if (awvalid && wvalid) ax_state <= AX_BRESP;
          else if (arvalid) begin
            ax_raddr_q <= araddr[ADDR_WIDTH-1:0];
            ax_state   <= AX_RRESP;
          end
        end
        AX_RRESP: if (r_rready) ax_state <= AX_IDLE;
        AX_BRESP: if (bready)   ax_state <= AX_IDLE;
        default: ;
      endcase
    end
  end

  assign bvalid   = (ax_state == AX_BRESP);
  assign bresp    = 2'b10;                 // SLVERR: ROM is read-only
  assign r_rvalid = (ax_state == AX_RRESP);
  assign r_rdata  = rom_decode(ax_raddr_q);
  assign r_rresp  = 2'b00;

endmodule
"""


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    data = src.read_bytes()
    words = read_image(src)
    if not words:
        raise SystemExit(f"{src}: empty image")
    text = emit(words, src.as_posix(), hashlib.sha256(data).hexdigest())
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_rom_rtl: {out} words={len(words)} image_sha256={hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    main()
